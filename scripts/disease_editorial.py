      '<details><summary>技术说明：时间换算与免疫公式</summary>','',
      '病原定义来自 `Pathogens.Definitions`：基准秒数乘 30，再除 3600 得到表中的生理小时。阶段标识为 `Exposed → Incubating → Symptomatic → Recovering`。','',
