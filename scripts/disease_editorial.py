    for id,agent,route,inc,sym,rec,sev in records:
        out.append(f'| [{specific[id][0]}](#{id}) | {ROUTES[route]} | {"30 秒" if id=="skin-fungal" else f"{inc:g}"} | {sym:g} | {rec:g} |')
